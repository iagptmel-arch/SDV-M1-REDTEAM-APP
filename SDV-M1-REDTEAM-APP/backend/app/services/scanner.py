SEMAPHORE_LIMIT = 100


async def _tcp_scan_port(host: str, port: int, timeout: float = 2.0) -> dict[str, Any]:
    """Teste un port TCP et retourne le résultat."""
    result: dict[str, Any] = {
        "port": port,
        "protocol": "tcp",
        "state": "closed",
        "name": None,
        "version": None,
    }
    try:
        _, writer = await asyncio.wait_for(
            asyncio.open_connection(host, port), timeout=timeout
        )
        result["state"] = "open"
        try:
            result["name"] = socket.getservbyport(port, "tcp")
        except (OSError, IndexError):
            # Port non répertorié dans /etc/services
            pass
        writer.close()
        await writer.wait_closed()
    except (ConnectionRefusedError, OSError, asyncio.TimeoutError):
        pass
    return result


async def _udp_scan_port(host: str, port: int, timeout: float = 2.0) -> dict[str, Any]:
    """Teste un port UDP (vérification par ICMP Port Unreachable)."""
    result: dict[str, Any] = {
        "port": port,
        "protocol": "udp",
        "state": "closed",
        "name": None,
        "version": None,
    }
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.settimeout(timeout)
        sock.sendto(b"\x00", (host, port))
        try:
            sock.recvfrom(1024)
            result["state"] = "open"
        except socket.timeout:
            # Pas de réponse → possiblement ouvert/filtré
            result["state"] = "open|filtered"
        except ConnectionRefusedError:
            pass
        finally:
            sock.close()

        if result["state"] != "closed":
            try:
                result["name"] = socket.getservbyport(port, "udp")
            except (OSError, IndexError):
                pass
    except OSError:
        pass
    return result


async def scan_ports(
    host: str,
    ports: list[int] | None = None,
    protocol: str = "tcp",
) -> list[dict[str, Any]]:
    """
    Scanne les ports d'un hôte et retourne les résultats.

    Args:
        host: Adresse IP ou hostname cible.
        ports: Liste de ports à scanner. Si None, utilise les 1000 ports communs.
        protocol: "tcp" ou "udp".

    Returns:
        Liste de dictionnaires : {port, protocol, state, name, version}
    """
    if ports is None:
        ports = COMMON_TCP_PORTS if protocol == "tcp" else COMMON_UDP_PORTS

    semaphore = asyncio.Semaphore(SEMAPHORE_LIMIT)
    scan_func = _tcp_scan_port if protocol == "tcp" else _udp_scan_port

    async def _scan_with_semaphore(p: int) -> dict[str, Any]:
        async with semaphore:
            return await scan_func(host, p)

    tasks = [_scan_with_semaphore(port) for port in ports]
    results = await asyncio.gather(*tasks)

    # Ne retourner que les ports ouverts ou potentiellement ouverts
    return [r for r in results if r["state"] != "closed"]
